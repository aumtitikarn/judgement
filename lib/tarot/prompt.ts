/** ข้อมูลผู้ถาม + ไพ่ที่เปิดได้ ประกอบเป็นข้อความเดียวที่ส่งให้โมเดล */
export function buildUserPrompt(
  querent: Querent,
  spread: Spread,
  question: string,
  draws: DrawnCard[],
  now = new Date(),
): string {
  const age = ageOf(querent, now);
  const today = new Intl.DateTimeFormat("th-TH", { dateStyle: "full" }).format(now);
  const isPack = spread.mode === "pack";

  const cards = draws.map((draw, index) => {
    const meaning = meaningOf(draw.card, draw.reversed);
    const header = isPack
      ? `คำถามข้อที่ ${index + 1}: "${draw.position}"`
      : `ใบที่ ${index + 1} — ตำแหน่ง "${draw.position}" (${draw.positionHint})`;

    return [
      header,
      `  ไพ่ที่ผู้ถามเลือกให้ข้อนี้: ${draw.card.nameTh} (${draw.card.name}) · ${
        SUIT_LABEL[draw.card.suit]
      } · ${draw.reversed ? "กลับหัว" : "หงาย"}`,
      `  คำสำคัญ: ${meaning.keywords.join(", ")}`,
      `  ความหมายพื้นฐาน (ใช้เป็นวัตถุดิบ ห้ามลอก): ${readingText(
        draw.card,
        draw.reversed,
        spread.meaningKey,
      )}`,
      `  คำแนะนำประจำไพ่: ${meaning.advice}`,
    ].join("\n");
  });

  const context = isPack
    ? [
        `แพ็กคำถามที่เลือก: ${spread.label}`,
        `ผู้ถามเลือกไพ่เองข้อละหนึ่งใบ รวม ${draws.length} ข้อ ตอบให้ครบทุกข้อตามลำดับ`,
      ]
    : [`หมวดที่เลือกดู: ${spread.label} — ${spread.tagline}`, `คำถามของผู้ถาม: "${question}"`];

  return [
    `วันที่เปิดไพ่: ${today}`,
    "",
    "ข้อมูลผู้ถาม",
    `- ชื่อ-นามสกุล: ${fullName(querent)}`,
    `- วันเวลาเกิด: ${birthLine(querent)}${age !== null ? ` (อายุประมาณ ${age} ปี)` : ""}`,
    `- ถิ่นเกิด: ${querent.birthCity} ประเทศ${querent.birthCountry}`,
    "",
    ...context,
    "",
    ...cards,
    "",
    `โปรดอ่านให้ครบ ใช้ [[CARD1]] ถึง [[CARD${draws.length}]] ทุกอัน`,
    "แล้วต่อด้วย [[SUMMARY]] [[ACTION]] และ [[TIMING]] ตามลำดับ",
  ].join("\n");
}
