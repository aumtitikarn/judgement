import type { MeaningKey } from "./types";

export interface QuestionPack {
  /** ลำดับชุดในหมวด ใช้เป็นส่วนหนึ่งของ URL */
  slug: string;
  label: string;
  questions: string[];
}

export interface PackCategory {
  slug: string;
  emoji: string;
  label: string;
  tagline: string;
  accent: string;
  /** ใช้ความหมายไพ่ด้านไหนมาเป็นวัตถุดิบให้ AI */
  meaningKey: MeaningKey;
  packs: QuestionPack[];
}

/**
 * แบ่งคำถามเป็นชุด ชุดละไม่เกิน 4 ข้อ และกระจายให้เท่ากันที่สุด
 * เพื่อไม่ให้มีชุดท้ายที่เหลือคำถามเดียวโดด ๆ (เช่น 5 ข้อ → 3+2 ไม่ใช่ 4+1)
 */
function toPacks(questions: string[], perPack = 4): QuestionPack[] {
  const count = Math.ceil(questions.length / perPack);
  const packs: QuestionPack[] = [];
  let start = 0;

  for (let index = 0; index < count; index += 1) {
    const take = Math.ceil((questions.length - start) / (count - index));
    packs.push({
      slug: String(index + 1),
      label: count === 1 ? "ชุดคำถาม" : `ชุดที่ ${index + 1}`,
      questions: questions.slice(start, start + take),
    });
    start += take;
  }

  return packs;
}

const category = (
  input: Omit<PackCategory, "packs"> & { questions: string[] },
): PackCategory => {
  const { questions, ...rest } = input;
  return { ...rest, packs: toPacks(questions) };
};

