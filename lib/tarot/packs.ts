export const CATEGORY_BY_SLUG = new Map(PACK_CATEGORIES.map((item) => [item.slug, item]));

export function findPack(categorySlug: string, packSlug: string) {
  const found = CATEGORY_BY_SLUG.get(categorySlug);
  const pack = found?.packs.find((item) => item.slug === packSlug);
  return found && pack ? { category: found, pack } : null;
}

export const TOTAL_QUESTIONS = PACK_CATEGORIES.reduce(
  (sum, item) => sum + item.packs.reduce((inner, pack) => inner + pack.questions.length, 0),
  0,
);

export const TOTAL_PACKS = PACK_CATEGORIES.reduce((sum, item) => sum + item.packs.length, 0);
